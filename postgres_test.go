// The types test: every value is stored, read back, and planned again, and
// must look unchanged; values written differently but stored the same must
// match; and the session's own settings mustn't matter.
const pgTypesSchema = `
CREATE TYPE mood AS ENUM ('sad', 'ok', 'happy');
CREATE DOMAIN percent AS integer CHECK (VALUE BETWEEN 0 AND 100);
CREATE TABLE things (
	id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	code text NOT NULL UNIQUE,
	i2 smallint, i4 integer, i8 bigint,
	num numeric, num2 numeric(10,2),
	f4 real, f8 double precision,
	flag boolean,
	t text, vc varchar(10), ch char(3),
	d date, ts timestamp, tstz timestamptz, tm time, iv interval,
	u uuid, j json, jb jsonb, bin bytea, ip inet,
	arr integer[], m mood, pct percent
)`

type pgCase struct {
	col  string
	toml string // the value as written in the seed
	want string // the value as PostgreSQL prints it, under the settings Bootstrapping uses
}

var pgCases = []pgCase{
	{"i2", `7`, "7"}, {"i4", `"0042"`, "42"}, {"i8", `9007199254740993`, "9007199254740993"},
	{"i4", `true`, "1"},
	{"num", `1.5`, "1.5"}, {"num", `"1.50"`, "1.50"}, {"num2", `7`, "7.00"}, {"num2", `"3.14159"`, "3.14"},
	{"f4", `0.1`, "0.1"}, {"f8", `0.1`, "0.1"}, {"f8", `1e300`, "1e+300"}, {"f8", `nan`, "NaN"}, {"f8", `-inf`, "-Infinity"},
	{"flag", `true`, "true"}, {"flag", `"yes"`, "true"}, {"flag", `"0"`, "false"},
	{"t", `"héllo, \"world\"\n"`, "héllo, \"world\"\n"}, {"t", `12`, "12"},
	{"vc", `"short"`, "short"}, {"ch", `"ab"`, "ab"},
	{"d", `2026-10-18`, "2026-10-18"}, {"d", `"Oct 18 2026"`, "2026-10-18"},
	{"ts", `2026-10-18T09:30:00`, "2026-10-18 09:30:00"},
	{"tstz", `2026-10-18T09:30:00+03:00`, "2026-10-18 06:30:00+00"}, {"tstz", `"2026-10-18 06:30Z"`, "2026-10-18 06:30:00+00"},
	{"tm", `09:30:00`, "09:30:00"},
	{"iv", `"1 day 2 hours"`, "1 day 02:00:00"}, {"iv", `"P1DT2H"`, "1 day 02:00:00"},
	{"u", `"A0EEBC99-9C0B-4EF8-BB6D-6BB9BD380A11"`, "a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11"},
	{"j", `"{\"b\": 1, \"a\": 2}"`, `{"b": 1, "a": 2}`}, {"jb", `"{\"b\": 1,   \"a\": 2}"`, `{"a": 2, "b": 1}`},
	{"bin", `"\\x00ff"`, `\x00ff`},
	{"ip", `"192.168.0.1/32"`, "192.168.0.1/32"},
	{"arr", `"{1, 2,3}"`, "{1,2,3}"},
	{"m", `"happy"`, "happy"},
	{"pct", `"50"`, "50"},
}

func TestPostgresTypes(t *testing.T) {
	b := pgBackend(t)
	ctx := context.Background()
	db := b.open(t)
	mustExec(t, db, pgTypesSchema)
	var rows strings.Builder
	rows.WriteString("table = \"things\"\nkey = \"code\"\n")
	for i, c := range pgCases {
		fmt.Fprintf(&rows, "[[row]]\ncode = \"r%02d\"\n%s = %s\n", i, c.col, c.toml)
	}
	set := setFrom(t, map[string]string{"things.toml": rows.String()})
	if _, err := bs.Apply(ctx, db, set, nil); err != nil {
		t.Fatal(err)
	}
	for i, c := range pgCases {
		got := query1(t, db, fmt.Sprintf(`SELECT CAST(%q AS text) FROM things WHERE code = ?`, c.col), fmt.Sprintf("r%02d", i))
		// Read under the session's defaults, which the test server leaves as
		// they come; the comparison below is the engine's own.
		if c.col != "tstz" && c.col != "f4" && c.col != "f8" && got != c.want {
			t.Errorf("%s = %s: stored %q, want %q", c.col, c.toml, got, c.want)
		}
	}
	// Planned again, nothing has changed, whatever the session's settings.
	for _, opt := range []string{"", "TimeZone=Pacific/Kiritimati", "DateStyle=German", "IntervalStyle=sql_standard", "extra_float_digits=-3", "bytea_output=escape"} {
		odd := db
		if opt != "" {
			k, v, _ := strings.Cut(opt, "=")
			var err error
			odd, err = sql.Open("postgres", pgURLWith(currentSchema(t, db))+"&"+k+"="+v)
			if err != nil {
				t.Fatal(err)
			}
			defer odd.Close()
		}
		p, err := bs.Preview(ctx, odd, set, nil)
		if err != nil {
			t.Fatalf("%s: %v", opt, err)
		}
		if p.Pending() {
			t.Fatalf("%s: values look changed: %s", opt, actions(p))
		}
	}
	// An admin writing the same value another way isn't an edit.
	mustExec(t, db, "UPDATE things SET num2 = 7.000 WHERE num2 = 7")
	mustExec(t, db, `UPDATE things SET jb = '{"a":2,"b":1}' WHERE jb IS NOT NULL`)
	mustExec(t, db, "UPDATE things SET tstz = '2026-10-18 01:30:00-05' WHERE tstz IS NOT NULL")
	if p, err := bs.Preview(ctx, db, set, nil); err != nil || p.Pending() {
		t.Fatalf("after rewriting the same values: %v %s", err, actions(p))
	}
	// A real edit is one.
	mustExec(t, db, "UPDATE things SET num2 = 7.01 WHERE num2 = 7")
	p, err := bs.Preview(ctx, db, set, nil)
	if err != nil {
		t.Fatal(err)
	}
	if got := actions(p); !strings.Contains(got, "keep-edit things/r06.num2") {
		t.Fatalf("an edit wasn't seen: %s", got)
	}
}

