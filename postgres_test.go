// A ledger further down the search path isn't this setup's: it is neither
// read nor written.
func TestPostgresLedgerInFirstSchemaOnly(t *testing.T) {
	b := pgBackend(t)
	other := b.open(t)
	mustExec(t, other, `CREATE TABLE roles (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text NOT NULL UNIQUE, name text)`)
	files := func(name string) map[string]string {
		return map[string]string{"roles.toml": "table = \"roles\"\nkey = \"code\"\n[[row]]\ncode = \"a\"\nname = \"" + name + "\"\n[[row]]\ncode = \"b\"\nname = \"B\"\n"}
	}
	(&fixture{t: t, db: other, ctx: context.Background()}).agree(files("A"))
	first := b.open(t)
	both, err := sql.Open("postgres", pgURLWith(currentSchema(t, first)+","+currentSchema(t, other)))
	if err != nil {
		t.Fatal(err)
	}
	defer both.Close()
	pgDBs.Store(both, true)
	// The roles table is found in the second schema, but its ledger is
	// not this path's: every row is adopted afresh.
	p, err := bs.Preview(context.Background(), both, setFrom(t, files("A2")), nil)
	if err != nil {
		t.Fatal(err)
	}
	if got := actions(p); got != "conflict roles/a.name; record roles/b" {
		t.Fatalf("got %s", got)
	}
}

func TestPostgresRetireColumnType(t *testing.T) {
	b := pgBackend(t)
	db := b.open(t)
	mustExec(t, db, `CREATE TABLE r (code text PRIMARY KEY, retired boolean); CREATE TABLE s (code text PRIMARY KEY, retired timestamptz)`)
	set := setFrom(t, map[string]string{"r.toml": "table = \"r\"\nkey = \"code\"\non_remove = { retire = \"retired\" }\n[[row]]\ncode = \"a\"\n"})
	if _, err := bs.Preview(context.Background(), db, set, nil); err == nil || !strings.Contains(err.Error(), "can't hold the time a row was retired") {
		t.Fatalf("got %v", err)
	}
	f := &fixture{t: t, db: db, ctx: context.Background()}
	seed := func(rows string) map[string]string {
		return map[string]string{"s.toml": "table = \"s\"\nkey = \"code\"\non_remove = { retire = \"retired\" }\n" + rows}
	}
	f.agree(seed("[[row]]\ncode = \"a\"\n[[row]]\ncode = \"b\"\n"))
	expect(t, f.agree(seed("[[row]]\ncode = \"a\"\n")), "retire s/b")
	if got := f.one("SELECT retired = '2026-11-02T08:00:00Z' FROM s WHERE code = 'b'"); got != "true" {
		t.Fatalf("retired at the apply's time: %s", got)
	}
}
