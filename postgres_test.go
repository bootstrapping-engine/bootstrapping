// An edit that points a reference at a row that doesn't exist is logged
// like any other when the seed's value lands.
func TestPostgresMissingReferenceInTheLog(t *testing.T) {
	b := pgBackend(t)
	db := b.open(t)
	mustExec(t, db, `CREATE TABLE roles (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text NOT NULL UNIQUE);
CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, login text NOT NULL UNIQUE, role_id bigint)`)
	f := &fixture{t: t, db: db, ctx: context.Background()}
	files := map[string]string{
		"roles.toml": "table = \"roles\"\nkey = \"code\"\n[[row]]\ncode = \"a\"\n",
		"users.toml": "table = \"users\"\nkey = \"login\"\n[columns]\nrole_id = \"seed\"\n[refs]\nrole_id = \"roles.code\"\n[[row]]\nlogin = \"bob\"\nrole_id = \"a\"\n",
	}
	f.agree(files)
	mustExec(t, db, "UPDATE users SET role_id = 999")
	expect(t, f.agree(files), "update users/bob.role_id")
	rep, err := bs.Explain(f.ctx, db, setFrom(t, files), "users", "bob", nil)
	if err != nil {
		t.Fatal(err)
	}
	last := rep.History[len(rep.History)-1]
	if last.Old != "(missing row 999)" || last.New != `"a"` {
		t.Fatalf("logged %q -> %q", last.Old, last.New)
	}
}

// Ids the seed sets in an identity column move its sequence on, so the
// application's next insert gets a fresh one.
func TestPostgresSeededIdsMoveTheSequence(t *testing.T) {
	b := pgBackend(t)
	db := b.open(t)
	mustExec(t, db, `CREATE TABLE roles (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text NOT NULL UNIQUE);
CREATE TABLE plans (id serial PRIMARY KEY, code text NOT NULL UNIQUE)`)
	f := &fixture{t: t, db: db, ctx: context.Background()}
	f.agree(map[string]string{
		"roles.toml": "table = \"roles\"\nkey = \"code\"\n[[row]]\ncode = \"a\"\nid = 1\n[[row]]\ncode = \"b\"\nid = 7\n",
		"plans.toml": "table = \"plans\"\nkey = \"code\"\n[[row]]\ncode = \"free\"\nid = 3\n",
	})
	mustExec(t, db, "INSERT INTO roles (code) VALUES ('app')")
	mustExec(t, db, "INSERT INTO plans (code) VALUES ('app')")
	if got := f.one("SELECT (SELECT id FROM roles WHERE code = 'app') || ' ' || (SELECT id FROM plans WHERE code = 'app')"); got != "8 4" {
		t.Fatalf("the application's ids: %s", got)
	}
	// A sequence already further on is left there.
	f.agree(map[string]string{
		"roles.toml": "table = \"roles\"\nkey = \"code\"\n[[row]]\ncode = \"a\"\nid = 1\n[[row]]\ncode = \"b\"\nid = 7\n[[row]]\ncode = \"c\"\nid = 5\n",
		"plans.toml": "table = \"plans\"\nkey = \"code\"\n[[row]]\ncode = \"free\"\nid = 3\n",
	})
	mustExec(t, db, "INSERT INTO roles (code) VALUES ('app2')")
	if got := f.one("SELECT id FROM roles WHERE code = 'app2'"); got != "9" {
		t.Fatalf("app2: %s", got)
	}
}

